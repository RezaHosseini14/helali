import { PERMISSIONS } from './permissions';
import { ROLE_NAMES } from './roles';

/** Default permission sets for system roles (seed + tests). Runtime source of truth is DB. */
export const ROLE_PERMISSIONS: Record<string, readonly string[]> = {
  [ROLE_NAMES.SUPER]: Object.values(PERMISSIONS),
  [ROLE_NAMES.ADMIN]: [
    PERMISSIONS.AUDIO_READ,
    PERMISSIONS.AUDIO_CREATE,
    PERMISSIONS.AUDIO_UPDATE,
    PERMISSIONS.AUDIO_DELETE,
    PERMISSIONS.VIDEO_READ,
    PERMISSIONS.VIDEO_CREATE,
    PERMISSIONS.VIDEO_UPDATE,
    PERMISSIONS.VIDEO_DELETE,
    PERMISSIONS.GALLERY_READ,
    PERMISSIONS.GALLERY_CREATE,
    PERMISSIONS.GALLERY_UPDATE,
    PERMISSIONS.GALLERY_DELETE,
    PERMISSIONS.CATEGORY_MANAGE,
    PERMISSIONS.COMMENT_MANAGE,
    PERMISSIONS.TWEET_READ,
    PERMISSIONS.TWEET_CREATE,
    PERMISSIONS.TWEET_UPDATE,
    PERMISSIONS.TWEET_DELETE,
    PERMISSIONS.USER_READ,
    PERMISSIONS.USER_CREATE,
    PERMISSIONS.USER_UPDATE,
    PERMISSIONS.USER_DELETE,
    PERMISSIONS.USER_MANAGE,
    PERMISSIONS.DASHBOARD_READ,
    PERMISSIONS.AUDIT_READ,
  ],
  [ROLE_NAMES.USER]: [
    PERMISSIONS.AUDIO_READ,
    PERMISSIONS.VIDEO_READ,
    PERMISSIONS.GALLERY_READ,
  ],
};

export function getPermissionsForRole(role: string): readonly string[] {
  if (role === ROLE_NAMES.SUPER) {
    return Object.values(PERMISSIONS);
  }

  return ROLE_PERMISSIONS[role] ?? [];
}
